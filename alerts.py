def _console_alert(message: str) -> None:
    """
    Print a timestamped warning to the terminal.
    Always active — zero dependencies.
    """
    timestamp = time.strftime("%H:%M:%S")
    border    = "=" * 60
    print(f"\n{border}")
    print(f"  🔥  ALERT [{timestamp}]")
    print(f"  {message}")
    print(f"{border}\n")


def _sound_alert() -> None:
    """
    Play an audible alert.

    Tries `playsound` first (install via: pip install playsound==1.2.2).
    Falls back to the terminal bell character if playsound is unavailable.

    To use a custom sound file, place it at assets/alert.mp3 and update
    the SOUND_FILE path below.
    """
    SOUND_FILE = "assets/alert.mp3"  # Optional — provide your own sound file

    try:
        from playsound import playsound
        import os
        if os.path.exists(SOUND_FILE):
            playsound(SOUND_FILE, block=False)
        else:
            # playsound installed but no sound file — use bell
            print("\a", end="", flush=True)
    except ImportError:
        # playsound not installed — terminal bell fallback
        print("\a", end="", flush=True)
    except Exception as e:
        # Never let a sound failure crash the app
        print(f"[alerts] Sound error (non-fatal): {e}")


