"""
alerts.py — Alert & Notification Module
AI Gas Stove Safety System

Centralises all alert output so you can swap in real notification methods
(sound, Telegram, SMS) without touching any other file.

Current implementations:
  • Console  — always active; prints a timestamped message.
  • Sound    — uses the `playsound` library if installed; falls back to
               the system bell (\\a) otherwise.

Stubbed-out (ready for extension):
  • Telegram bot message
  • Email / SMTP
  • Mobile push notification
  • Raspberry Pi GPIO buzzer
"""

import time
import threading


# ── Throttle: don't spam the same alert more than once per N seconds ───────
_ALERT_COOLDOWN_SECONDS = 3.0
_last_alert_time: float = 0.0          # Module-level state
_last_alert_message: str = ""


def trigger_alert(message: str) -> None:
    """
    Main entry point called by main.py when risk_level == "HIGH".

    Checks the cooldown, then fires all enabled alert channels in
    non-blocking background threads so they don't stall the video loop.

    Args:
        message: The warning text generated by logic.py.
    """
    global _last_alert_time, _last_alert_message

    now = time.time()
    same_message   = message == _last_alert_message
    within_cooldown = (now - _last_alert_time) < _ALERT_COOLDOWN_SECONDS

    # Suppress duplicate alerts within the cooldown window
    if same_message and within_cooldown:
        return

    _last_alert_time    = now
    _last_alert_message = message

    # Fire each alert channel in its own thread (non-blocking)
    _run_in_thread(_console_alert, message)
    _run_in_thread(_sound_alert)

    # Uncomment when you implement these:
    # _run_in_thread(_telegram_alert, message)
    # _run_in_thread(_email_alert, message)
    # _run_in_thread(_gpio_buzzer_alert)


